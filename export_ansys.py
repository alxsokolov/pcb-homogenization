#!/usr/bin/env python3
"""
Export a quadtree homogenization result (quadtree.py's mesh/quadtree.json)
to an ANSYS Mechanical APDL input script: one rectangular block volume per
leaf, each assigned its own orthotropic elastic + CTE material from that
leaf's homogenized properties, glued into a conformal assembly.

Works with quadtree.json produced by either homogenizer (default
Voigt-Reuss, or --homogenizer ml) since both write the same leaf schema
(E_xy_voigt_GPa, E_z_reuss_GPa, alpha_xy_voigt_per_K, alpha_z_reuss_per_K,
phi_3D) -- see homogenization.voigt_reuss_bounds() and
ml_homogenization.predict_leaf_properties().

nu_eff per leaf = phi_3D*nu_cu + (1-phi_3D)*nu_fr4 (volume-fraction
weighted, applied isotropically as PRXY=PRYZ=PRXZ) -- Voigt-Reuss gives no
effective Poisson's ratio directly, same flagged simplification already
used by simulate_joint_qoi.py's assign_uniform_from_quadtree().

Output is a batch APDL script (.inp), the standard exchange format for
bringing scripted geometry+materials into ANSYS:
  - Standalone: `mapdl -b -i model.inp -o model.out` in Mechanical APDL.
  - Workbench: add a "Mechanical APDL" system to the project schematic and
    point its input file at model.inp, or paste the script into a
    Commands (APDL) object in an existing Mechanical session.
Meshing and loads/BCs are deliberately left to the user in Workbench
Mechanical unless --mesh is given.

Usage:
    python export_ansys.py data/samples/rv3032_real
    python export_ansys.py data/samples/rv3032_real --out model.inp --mesh --mesh-size-mm 0.5
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from homogenization import load_materials, orthotropic_engineering_constants

_UNITS_NOTE = "length=mm, force=N, stress=MPa, temperature=degC (Standard NMM unit system)"


def _leaf_material_lines(mat_id: int, leaf: dict, materials: dict) -> list[str]:
    c = orthotropic_engineering_constants(leaf, materials)
    return [
        f"MP,EX,{mat_id},{c['EX']:.6g}",
        f"MP,EY,{mat_id},{c['EY']:.6g}",
        f"MP,EZ,{mat_id},{c['EZ']:.6g}",
        f"MP,PRXY,{mat_id},{c['PRXY']:.6g}",
        f"MP,PRYZ,{mat_id},{c['PRYZ']:.6g}",
        f"MP,PRXZ,{mat_id},{c['PRXZ']:.6g}",
        f"MP,GXY,{mat_id},{c['GXY']:.6g}",
        f"MP,GYZ,{mat_id},{c['GYZ']:.6g}",
        f"MP,GXZ,{mat_id},{c['GXZ']:.6g}",
        f"MP,ALPX,{mat_id},{c['ALPX']:.6g}",
        f"MP,ALPY,{mat_id},{c['ALPY']:.6g}",
        f"MP,ALPZ,{mat_id},{c['ALPZ']:.6g}",
    ]


def build_apdl_script(qt: dict, meta: dict, materials: dict, sample_name: str,
                      mesh: bool, mesh_size_mm: float | None, ref_temp_c: float) -> str:
    leaves = qt["leaves"]
    Lz_mm = meta["stackup"]["total_thickness_mm"]

    lines = [
        "/BATCH",
        "/PREP7",
        f"! Generated by export_ansys.py from {sample_name}/mesh/quadtree.json",
        f"! Board: {meta['board']['width_mm']}x{meta['board']['height_mm']} mm, "
        f"thickness {Lz_mm} mm, {len(leaves)} leaves (max_level={qt.get('max_level')}, "
        f"criterion={qt.get('criterion')})",
        f"! Units: {_UNITS_NOTE}",
        "! Each leaf -> one block volume + one orthotropic elastic/CTE material "
        "(MAT id == leaf index, 1-based, same order both loops below)",
        "! nu_eff = phi_3D*nu_cu + (1-phi_3D)*nu_fr4 -- Voigt-Reuss has no effective "
        "Poisson's ratio; same simplification as "
        "simulate_joint_qoi.py's assign_uniform_from_quadtree()",
        "",
        "ET,1,SOLID186",
        f"TREF,{ref_temp_c:.6g}   ! stress-free reference temperature -- adjust to your "
        "actual assembly/solder-reflow temperature",
        "",
    ]

    for i, leaf in enumerate(leaves, start=1):
        lines.append(f"! -- leaf {i}: bbox_mm={leaf['bbox_mm']} level={leaf['level']} "
                    f"phi_top={leaf['phi_top']:.4g} phi_bot={leaf['phi_bot']:.4g}")
        lines.extend(_leaf_material_lines(i, leaf, materials))
    lines.append("")

    for i, leaf in enumerate(leaves, start=1):
        x0, y0, x1, y1 = leaf["bbox_mm"]
        lines.append(f"BLOCK,{x0:.6f},{x1:.6f},{y0:.6f},{y1:.6f},0,{Lz_mm:.6f}   ! leaf {i} -> volume {i}")
    lines.append("")

    lines.append("VGLUE,ALL   ! split shared faces between adjacent leaves so the mesh "
                 "will be conformal across material boundaries -- does not renumber volumes")
    lines.append("")

    for i in range(1, len(leaves) + 1):
        lines.append(f"VSEL,S,VOLU,,{i}")
        lines.append(f"VATT,{i},,1")
        if mesh:
            if mesh_size_mm:
                lines.append(f"ESIZE,{mesh_size_mm:.6g},0")
            lines.append(f"VMESH,{i}")
    lines.append("")
    lines.append("ALLSEL,ALL")
    lines.append("FINISH")
    return "\n".join(lines) + "\n"


def export_ansys(sample_dir: Path, out_path: Path, materials: dict,
                 mesh: bool = False, mesh_size_mm: float | None = None,
                 ref_temp_c: float = 20.0) -> Path:
    qt_path = sample_dir / "mesh" / "quadtree.json"
    if not qt_path.exists():
        sys.exit(f"Run quadtree.py first -- not found: {qt_path}")
    with open(qt_path) as f:
        qt = json.load(f)
    with open(sample_dir / "metadata.json") as f:
        meta = json.load(f)

    script = build_apdl_script(qt, meta, materials, sample_dir.name, mesh, mesh_size_mm, ref_temp_c)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(script)
    return out_path


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Export a quadtree.py result to an ANSYS Mechanical APDL input script.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("sample_dir", type=Path)
    parser.add_argument("--out", type=Path, default=None,
                        help="Output .inp path (default: <sample_dir>/mesh/model.inp)")
    parser.add_argument("--materials", type=Path, default=Path("configs/materials.yaml"))
    parser.add_argument("--mesh", action="store_true",
                        help="Also emit VMESH per volume. Default off: geometry+materials "
                             "only, so meshing is done with Workbench Mechanical's own "
                             "mesh controls.")
    parser.add_argument("--mesh-size-mm", type=float, default=None,
                        help="Global ESIZE hint, only used with --mesh.")
    parser.add_argument("--ref-temp-c", type=float, default=20.0,
                        help="Stress-free reference temperature (TREF) in degC.")
    args = parser.parse_args()

    if not args.sample_dir.exists():
        sys.exit(f"Not found: {args.sample_dir}")

    materials = load_materials(args.materials)
    out_path = args.out or (args.sample_dir / "mesh" / "model.inp")
    export_ansys(args.sample_dir, out_path, materials,
                mesh=args.mesh, mesh_size_mm=args.mesh_size_mm, ref_temp_c=args.ref_temp_c)

    with open(args.sample_dir / "mesh" / "quadtree.json") as f:
        n_leaves = json.load(f)["n_leaves"]
    print(f"Wrote {out_path}  ({n_leaves} leaves -> {n_leaves} volumes/materials)")
    if not args.mesh:
        print("Geometry + materials only (no --mesh) -- mesh and add loads/BCs in "
             "Workbench Mechanical after import.")


if __name__ == "__main__":
    main()
